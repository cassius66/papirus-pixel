#!/usr/bin/env python3
"""
papirus-pixel.py: add a pixel art theme, Papirus-Pixel, to a Papirus fork.

It lives in pixel/ of a papirus-icon-theme checkout. It reads one existing
theme (default Papirus-Dark) and writes a new theme folder next to it:

    Papirus/  Papirus-Dark/  Papirus-Light/  Papirus-Pixel/   <- generated

Papirus-Pixel holds only the redrawn icons and their aliases, plus the extra
aliases in pixel/aliases.txt for app icons Papirus does not draw. Its
index.theme inherits from the base theme, so symbolic, panel and animation
icons come from Papirus-Dark unchanged. No upstream file is modified, so
merging upstream never conflicts.

What happens to each icon
  apps, places, mimetypes, devices, categories at 24 px and larger:
      drawn from the 64 px original on a 24 by 24 grid, recolored to the
      palette, with a 1 pixel dark outline
  every other color icon, and all icons below 24 px:
      drawn from its own file on a grid equal to its size, no outline
  symbolic, panel, animations: not written, inherited from the base theme

Requirements
  Python 3.8 or newer and one SVG renderer:
    rsvg-convert   sudo pacman -S librsvg   (already present on most GNOME systems)
    resvg_py       or: pip install resvg-py

Build and install, for the current user only
  python3 pixel/papirus-pixel.py
  make install PREFIX=$HOME/.local ICON_THEMES=Papirus-Pixel
  gsettings set org.gnome.desktop.interface icon-theme Papirus-Pixel

  Papirus-Pixel inherits from Papirus-Dark, so Papirus must be installed too,
  for example with pacman -S papirus-icon-theme. Install only Papirus-Pixel
  into ~/.local/share/icons: launchers that take the first icon file they
  find, such as Omarchy's, then pick Papirus-Pixel over every other theme.

Keep the fork up to date
  git remote add upstream https://github.com/PapirusDevelopmentTeam/papirus-icon-theme   # once
  git fetch upstream && git merge upstream/master
  python3 pixel/papirus-pixel.py

  Papirus-Pixel is gitignored. Releases carry the built theme.

Options
  -p, --palette P   built in palette name, a comma list of hex colors, or any
                    file containing hex colors, such as an Omarchy theme file
                    ~/.local/state/omarchy/current/theme/colors.toml
                    (default: sweetie-16; list them with --list-palettes)
  -b, --base NAME   theme to convert (default: Papirus-Dark)
  -n, --name NAME   new theme folder name (default: Papirus-Pixel)
  -j, --jobs N      parallel workers (default: number of CPUs)

More than one palette
  python3 pixel/papirus-pixel.py -p gruvbox-dark -n Papirus-Pixel-Gruvbox

A run redraws about 20,000 icons and takes a few minutes on 8 cores.
Papirus is GPL 3.0, so the generated theme is GPL 3.0 as well.
This fork's README is .github/README.md; the root README.md is upstream's.
"""
