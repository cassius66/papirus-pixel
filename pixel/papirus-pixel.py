# ---------------------------------------------------------------- palette

def parse_palette(spec):
    if spec in PALETTES:
        return ["#" + h for h in PALETTES[spec].split()]
    path = os.path.expanduser(spec)
    text = open(path, encoding="utf8").read() if os.path.isfile(path) else spec
    cols = list(dict.fromkeys("#" + h.lower() for h in re.findall(r"(?:#|0x)([0-9a-fA-F]{6})\b", text)))
    if len(cols) < 2:
        sys.exit(f"palette {spec!r}: need at least 2 hex colors, found {len(cols)}")
    return cols


def hex2rgb(h):
    h = h.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def oklab(rgb):
    def lin(c):
        c /= 255
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (lin(c) for c in rgb)
    l = (0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b) ** (1 / 3)
    m = (0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b) ** (1 / 3)
    s = (0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b) ** (1 / 3)
    return (0.2104542553 * l + 0.7936177850 * m - 0.0040720468 * s,
            1.9779984951 * l - 2.4285922050 * m + 0.4505937099 * s,
            0.0259040371 * l + 0.7827717662 * m - 0.8086757660 * s)


PAL = []      # [(rgb, oklab)], set per worker
INK = None    # darkest palette color, used for outlines


def set_palette(colors):
    global PAL, INK
    PAL = [(hex2rgb(c), oklab(hex2rgb(c))) for c in colors]
    INK = min(PAL, key=lambda p: p[1][0])[0]
    nearest.cache_clear()


@functools.lru_cache(maxsize=65536)
def nearest(rgb):
    lab = oklab(rgb)
    return min(PAL, key=lambda p: sum((a - b) ** 2 for a, b in zip(lab, p[1])))[0]


# ---------------------------------------------------------------- rendering

def _renderer():
    try:
        import resvg_py
        return lambda svg, px: resvg_py.svg_to_bytes(svg_string=svg, width=px, height=px)
    except ImportError:
        pass
    if shutil.which("rsvg-convert"):
        return lambda svg, px: subprocess.run(
            ["rsvg-convert", "-w", str(px), "-h", str(px), "-f", "png"],
            input=svg.encode(), capture_output=True, check=True).stdout
    sys.exit("no SVG renderer: install librsvg (rsvg-convert) or pip install resvg-py")


RENDER = None


def render(svg, px):
    """Return px rows of RGBA tuples."""
    return decode_png(RENDER(svg, px))


def decode_png(data):
    """Minimal decoder for the 8 bit RGB or RGBA, non interlaced PNGs both renderers emit.

    rsvg-convert drops the alpha channel when an icon has no transparency.
    """
    pos, idat, w, h, bpp = 8, b"", 0, 0, 4
    while pos < len(data):
        n, kind = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + n]
        if kind == b"IHDR":
            w, h, depth, ctype, _, _, interlace = struct.unpack(">IIBBBBB", body)
            if depth != 8 or ctype not in (2, 6) or interlace:
                raise ValueError(f"unsupported PNG: depth {depth}, type {ctype}, interlace {interlace}")
            bpp = 4 if ctype == 6 else 3
        elif kind == b"IDAT":
            idat += body
        pos += 12 + n
    raw, stride, prev, rows, i = zlib.decompress(idat), w * bpp, bytearray(w * bpp), [], 0
    for _ in range(h):
        f, line = raw[i], bytearray(raw[i + 1:i + 1 + stride])
        i += 1 + stride
        for x in range(stride):
            a = line[x - bpp] if x >= bpp else 0
            b = prev[x]
            c = prev[x - bpp] if x >= bpp else 0
            if f == 1:
                line[x] = (line[x] + a) & 255
            elif f == 2:
                line[x] = (line[x] + b) & 255
            elif f == 3:
                line[x] = (line[x] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append([tuple(line[x:x + 4]) if bpp == 4 else (*line[x:x + 3], 255) for x in range(0, stride, bpp)])
        prev = line
    return rows


# ---------------------------------------------------------------- the filter

ELEMENT = re.compile(r"<(path|rect|circle|ellipse)\b[^>]*/>")
OPACITY = re.compile(r'(?<![-\w])opacity([=:]\s*"?)([0-9.]+)')


def flatten(svg):
    """Delete translucent shadow and highlight layers.

    Papirus also draws small details in translucent black, so only layers
    spanning at least 70% of the icon count as shading.
    """
    root = re.search(r"<svg\b[^>]*>", svg)
    if not root:
        return svg

    def keep(m):
        el = m.group(0)
        op = OPACITY.search(el)
        if not op or float(op.group(2)) > 0.35:
            return el
        alpha = [[px[3] for px in row] for row in render(root.group(0) + OPACITY.sub(r"opacity\g<1>1", el) + "</svg>", 64)]
        ys = [y for y, row in enumerate(alpha) if any(row)]
        xs = [x for x in range(64) if any(row[x] for row in alpha)]
        if ys and max(xs[-1] - xs[0], ys[-1] - ys[0]) + 1 >= 0.7 * 64:
            return ""
        return el
    return ELEMENT.sub(keep, svg)


def recolor(svg):
    return HEX.sub(lambda m: "#%02x%02x%02x" % nearest(hex2rgb(m.group(0))), svg)


def pixelate(svg, grid, outline):
    """Render at 4x and give each grid cell its most common palette color."""
    big, s = render(svg, grid * SUPERSAMPLE), SUPERSAMPLE
    cells = [[None] * grid for _ in range(grid)]
    for y in range(grid):
        for x in range(grid):
            solid = [p for p in (big[y * s + j][x * s + i] for j in range(s) for i in range(s)) if p[3] >= 128]
            if len(solid) * 2 >= s * s:
                cells[y][x] = Counter(nearest(p[:3]) for p in solid).most_common(1)[0][0]
    if outline:
        edge = [(x, y) for y in range(grid) for x in range(grid) if cells[y][x] is None and any(
            0 <= x + dx < grid and 0 <= y + dy < grid and cells[y + dy][x + dx] is not None
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))]
        for x, y in edge:
            cells[y][x] = INK
    return cells


def to_svg(cells):
    grid, rects = len(cells), []
    for y, row in enumerate(cells):
        x = 0
        while x < grid:
            c = row[x]
            if c is None:
                x += 1
                continue
            x0 = x
            while x < grid and row[x] == c:
                x += 1
            rects.append(f'<rect x="{x0}" y="{y}" width="{x - x0}" height="1" fill="#%02x%02x%02x"/>' % c)
    if not rects:
        return None
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{grid}" height="{grid}" '
            f'viewBox="0 0 {grid} {grid}" shape-rendering="crispEdges">\n{"".join(rects)}\n</svg>\n')


def convert(job):
    """Worker: (source file, grid, outline) -> pixel SVG, None when nothing survives, or an error."""
    src, grid, outline = job
    try:
        return job, to_svg(pixelate(recolor(flatten(open(src, encoding="utf8").read())), grid, outline))
    except Exception as e:  # one broken icon must not stop the run
        return job, f"ERROR {e}"


def init_worker(colors):
    global RENDER
    RENDER = _renderer()
    set_palette(colors)


# ---------------------------------------------------------------- symlinks

@functools.lru_cache(maxsize=None)
def link_target(path):
    """Target text of a symlink.

    Also reads git checkouts made without symlink support, where each link
    is a small text file holding its target path.
    """
    if os.path.islink(path):
        return os.readlink(path)
    if os.path.isfile(path) and os.path.getsize(path) < 512:
        try:
            text = open(path, encoding="utf8").read().strip()
        except (UnicodeDecodeError, OSError):
            return None
        if text and "<" not in text and "\n" not in text and "=" not in text \
                and os.path.lexists(os.path.join(os.path.dirname(path), text)):
            return text
    return None


def resolve(path):
    """Follow links in every component of path; return the real path or None."""
    parts = os.path.abspath(path).split(os.sep)
    for _ in range(64):
        acc = parts[0] + os.sep
        for i, part in enumerate(parts[1:], 1):
            nxt = os.path.join(acc, part)
            t = link_target(nxt)
            if t is not None:
                parts = os.path.normpath(os.path.join(acc, t)).split(os.sep) + parts[i + 1:]
                break
            if not os.path.lexists(nxt):
                return None
            acc = nxt
        else:
            return acc
    return None


# ---------------------------------------------------------------- planning

class Plan:
    """Walk the base theme and decide what each output path becomes.

    A mirror is a (source folder, output folder) pair whose layout is copied
    one to one. The base theme is the first mirror. A link that leaves every
    mirror, such as Papirus-Dark/64x64 -> ../Papirus/64x64, is entered as a
    new mirror, so links inside it are kept as links.
    """

    def __init__(self, base, out):
        self.base, self.out = base, out
        self.converts, self.links = [], []

    def walk(self, src_dir, out_dir, mirrors, rel):
        for name in sorted(os.listdir(src_dir)):
            path, out, sub = os.path.join(src_dir, name), os.path.join(out_dir, name), rel + (name,)
            if len(sub) == 2 and name in INHERITED:
                continue
            t = link_target(path)
            if t is not None:
                target = os.path.normpath(os.path.join(src_dir, t))
                mapped = next((os.path.join(o, os.path.relpath(target, s)) for s, o in mirrors
                               if target == s or target.startswith(s + os.sep)), None)
                if mapped:
                    self.links.append((out, os.path.relpath(mapped, out_dir).replace(os.sep, "/")))
                    continue
                path = resolve(path)
                if path is None:
                    continue
                if os.path.isdir(path):
                    self.walk(path, out, mirrors + [(path, out)], sub)
                    continue
            if os.path.isdir(path):
                self.walk(path, out, mirrors, sub)
            else:
                self.file(path, out, sub)

    def file(self, path, out, rel):
        size = re.match(r"(\d+)x\d+$", rel[0]) if len(rel) == 3 else None
        if not size or not path.endswith(".svg"):
            return
        size, category = int(size.group(1)), rel[1]
        if size >= GRID and category in UPSCALED:
            src = next((s for s in (resolve(os.path.join(self.base, f"{n}x{n}", category, rel[2]))
                                    for n in SOURCE_SIZES) if s), path)
            self.converts.append((out, (src, GRID, True), path))
        else:
            self.converts.append((out, (path, size, False), path))


# ---------------------------------------------------------------- writing

def write_index(base, out, name):
    text = open(os.path.join(base, "index.theme"), encoding="utf8").read()
    inherits = re.search(r"^Inherits=(.*)$", text, re.M)
    text = re.sub(r"^Name=.*$", f"Name={name}", text, flags=re.M)
    text = re.sub(r"^Comment=.*$", f"Comment=Pixel art Papirus, {MARKER}", text, flags=re.M)
    text = re.sub(r"^Inherits=.*$", "Inherits=" + ",".join(
        [os.path.basename(base)] + (inherits.group(1).split(",") if inherits else ["hicolor"])), text, flags=re.M)

    def keep_dirs(m):
        dirs = [d for d in m.group(2).split(",") if os.path.isdir(os.path.join(out, d))]
        return f"{m.group(1)}={','.join(dirs)}"
    text = re.sub(r"^(Directories|ScaledDirectories)=(.*)$", keep_dirs, text, flags=re.M)
    with open(os.path.join(out, "index.theme"), "w", encoding="utf8") as f:
        f.write(text)


def place_links(links):
    """Create symlinks; where the OS refuses (Windows), copy the target instead."""
    fallback = []
    for out, target in links:
        os.makedirs(os.path.dirname(out), exist_ok=True)
        try:
            os.symlink(target, out)
        except OSError:
            fallback.append((out, target))
    dropped = 0
    while fallback:
        waiting = {o for o, _ in fallback}
        rest = []
        for out, target in fallback:
            src = os.path.normpath(os.path.join(os.path.dirname(out), target))
            blocked = src in waiting or any(w.startswith(src + os.sep) for w in waiting)
            if os.path.exists(src) and not blocked:
                (shutil.copytree if os.path.isdir(src) else shutil.copyfile)(src, out)
            elif os.path.exists(src) or blocked:
                rest.append((out, target))
            else:
                dropped += 1    # target will never exist
        if len(rest) == len(fallback):
            break               # a cycle; leave the remaining links out
        fallback = rest
    dropped += len(fallback)
    while True:                 # a dangling symlink can leave another one dangling
        broken = [out for out, _ in links if os.path.islink(out) and not os.path.exists(out)]
        if not broken:
            return dropped
        for out in broken:
            os.remove(out)
        dropped += len(broken)


def read_aliases(path):
    """(name, target) pairs from aliases.txt, one pair per line, # comments."""
    if not os.path.isfile(path):
        return []
    pairs = []
    for line in open(path, encoding="utf8"):
        words = line.split("#", 1)[0].split()
        if len(words) == 2:
            pairs.append(tuple(words))
    return pairs


def place_aliases(out, aliases):
    """Link each alias to its target in every apps folder that has the target."""
    made = 0
    for size in sorted(os.listdir(out)):
        apps = os.path.join(out, size, "apps")
        if os.path.islink(os.path.join(out, size)) or not os.path.isdir(apps):
            continue
        for name, target in aliases:
            link = os.path.join(apps, name + ".svg")
            if os.path.exists(os.path.join(apps, target + ".svg")) and not os.path.lexists(link):
                os.symlink(target + ".svg", link)
                made += 1
    return made


def main():
    ap = argparse.ArgumentParser(description="Add the Papirus-Pixel theme to a Papirus checkout.",
                                 formatter_class=argparse.RawDescriptionHelpFormatter, epilog=__doc__)
    ap.add_argument("repo", nargs="?", default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                    help="papirus-icon-theme checkout (default: parent of this script's folder)")
    ap.add_argument("-p", "--palette", default="sweetie-16")
    ap.add_argument("-b", "--base", default="Papirus-Dark")
    ap.add_argument("-n", "--name", default="Papirus-Pixel")
    ap.add_argument("-j", "--jobs", type=int, default=os.cpu_count())
    ap.add_argument("--list-palettes", action="store_true")
    a = ap.parse_args()

    if a.list_palettes:
        for k, v in PALETTES.items():
            print(f"{k:18} {len(v.split())} colors")
        return

    colors = parse_palette(a.palette)
    base = os.path.join(os.path.abspath(a.repo), a.base)
    out = os.path.join(os.path.abspath(a.repo), a.name)
    if not os.path.isfile(os.path.join(base, "index.theme")):
        sys.exit(f"no theme at {base}; run this in a papirus-icon-theme checkout or pass its path")
    if os.path.lexists(out):
        index = os.path.join(out, "index.theme")
        if not (os.path.isfile(index) and any(m in open(index, encoding="utf8").read() for m in (MARKER,) + OLD_MARKERS)):
            sys.exit(f"{out} exists and was not made by papirus-pixel.py; not touching it")
        print(f"replacing previous {a.name}")
        shutil.rmtree(out)

    plan = Plan(base, out)
    print(f"scanning {base}", flush=True)
    plan.walk(base, out, [(base, out)], ())
    jobs = sorted({job for _, job, _ in plan.converts})
    print(f"{len(plan.converts)} icons from {len(jobs)} drawings, {len(plan.links)} aliases; "
          f"palette {a.palette}, {len(colors)} colors", flush=True)

    results = {}
    with multiprocessing.Pool(a.jobs, init_worker, (colors,)) as pool:
        for n, (job, svg) in enumerate(pool.imap_unordered(convert, jobs, chunksize=16), 1):
            results[job] = svg
            if n % 2000 == 0 or n == len(jobs):
                print(f"  drawn {n}/{len(jobs)}", flush=True)

    kept, errors = 0, []
    for path, job, original in plan.converts:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        svg = results[job]
        if svg is None or svg.startswith("ERROR"):
            if svg:
                errors.append(f"{job[0]}: {svg[6:]}")
            kept += 1
            shutil.copyfile(original, path)
        else:
            with open(path, "w", encoding="utf8") as f:
                f.write(svg)
    broken = place_links(plan.links)
    extra = place_aliases(out, read_aliases(os.path.join(os.path.dirname(os.path.abspath(__file__)), "aliases.txt")))
    write_index(base, out, a.name)

    for e in errors[:10]:
        print("error:", e)
    print(f"done: {a.name} written to {out}\n"
          f"  {len(plan.converts) - kept} icons redrawn, {kept} kept as original "
          f"({len(errors)} errors), {len(plan.links) - broken} aliases, {broken} dangling aliases dropped, "
          f"{extra} links from aliases.txt")


if __name__ == "__main__":
    main()
